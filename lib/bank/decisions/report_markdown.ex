  # --- footer / hygiene ---------------------------------------------------

  defp footer do
    """

    ---

    *This report is replay-derived from persisted decision, audit,
    and execution rows. No business logic was re-run during
    rendering. The report does not assert ongoing safety,
    post-decision compliance, or production readiness. Field values
    reflect what was recorded at the time of decision/execution.
    Operator-supplied free-text reasons are intentionally redacted
    here; consult the underlying `decision_envelopes` row for
    forensic review with appropriate database access.*
    """
  end

  # --- shared helpers -----------------------------------------------------

  defp section_missing(title, reason) do
    [
      "## ",
      title,
      "\n",
      "\n",
      "_(missing — ",
      reason || "no detail recorded",
      ")_\n"
    ]
  end

  defp kv_row(label, value) do
    ["| ", label, " | `", to_string(value || "(none)"), "` |\n"]
  end

  defp short(nil), do: "(none)"

  defp short(value) when is_binary(value) do
    case String.length(value) do
      n when n <= @id_short_chars -> value
      _ -> binary_part(value, 0, @id_short_chars) <> "…"
    end
  end

  defp short(other), do: to_string(other)

  # --- final_reason allowlist (#249 P2) -----------------------------------
  #
  # `execution_plan.final_reason` is set by:
  #
  #   * runtime atom strings (`runtime_paused`, `chain_paused`,
  #     `delegation_not_active`, `operator_requested`, `sandbox_seed`)
  #   * `target_not_resolvable:<atom_cause>` from
  #     `lib/bank/runtime/workers/run_execution.ex`
  #   * `adapter_rejected:<status>:<summary>` from the same module
  #     (the `<summary>` slice can be up to 80 chars of arbitrary
  #     adapter response body)
  #   * adapter callback `params["reason"]` for `execution.reverted`
  #     and `execution.aborted` in `lib/bank/decisions.ex` — fully
  #     untrusted operator/provider free text
  #
  # Default-deny: only render values that match an explicit
  # allowlisted shape. The `adapter_rejected` summary slice is
  # dropped (status code only is rendered) so a stray PEM marker /
  # Bearer token / token URL hidden inside an adapter error body
  # cannot leak into the Markdown report. Free text falls through to
  # `(redacted free-text reason)`.

  defp safe_final_reason(nil), do: "(none)"
  defp safe_final_reason(""), do: "(none)"

  defp safe_final_reason(reason) when is_binary(reason) do
    cond do
      reason in @safe_final_reason_atoms -> reason
      target_unresolvable_match?(reason) -> reason
      adapter_rejected_status_only(reason) != :no_match -> adapter_rejected_status_only(reason)
      true -> "(redacted free-text reason)"
    end
  end

  defp safe_final_reason(_), do: "(redacted free-text reason)"

  defp target_unresolvable_match?("target_not_resolvable:" <> cause),
    do: cause in @safe_target_unresolvable_causes

  defp target_unresolvable_match?(_), do: false

  # `adapter_rejected:<status>[:<summary>]`. Render only the prefix
  # + numeric status; drop the summary regardless of content because
  # `summarise_body/1` can put arbitrary adapter bytes there.
  defp adapter_rejected_status_only("adapter_rejected:" <> rest) do
    case String.split(rest, ":", parts: 2) do
      [status] ->
        if numeric_status?(status), do: "adapter_rejected:#{status}", else: :no_match

      [status, _summary] ->
        if numeric_status?(status), do: "adapter_rejected:#{status}", else: :no_match
    end
  end

  defp adapter_rejected_status_only(_), do: :no_match

  defp numeric_status?(s) when is_binary(s) do
    s != "" and String.match?(s, ~r/^\d+$/)
  end

  # --- raw target address allowlist (#250 P2) -----------------------------
  #
  # `Bank.Intents` accepts any non-empty `target_raw_address`
  # string. Agents/operators can therefore paste arbitrary content
  # (Authorization headers, `sk_(test|live)_…` tokens, RPC URLs
  # with embedded credentials, PEM markers) and have it render
  # verbatim into the exported decision report. Default-deny
  # against the EVM `0x[a-f0-9]{40}` shape (case-insensitive on
  # the hex body), which is the only address shape any v0.1 chain
  # in the codebase emits (`base`, `ethereum`, `base-sepolia`,
  # `sepolia`, `goerli`). Anything else collapses to
  # `(redacted non-address raw target)` so the export still tells
  # a reviewer that a raw_address target was set, just not what
  # operator-supplied bytes were in it.

  @evm_raw_address_regex ~r/^0x[a-fA-F0-9]{40}$/

  defp safe_raw_address(nil), do: "(none)"
  defp safe_raw_address(""), do: "(none)"

  defp safe_raw_address(value) when is_binary(value) do
    if String.match?(value, @evm_raw_address_regex),
      do: value,
      else: "(redacted non-address raw target)"
  end

  defp safe_raw_address(_), do: "(redacted non-address raw target)"
end
