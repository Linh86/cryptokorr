  # --- stablecoin routes ---------------------------------------------------

  defp stablecoin_routes_section([]) do
    [
      "## Stablecoin route evidence\n",
      "\n",
      "_(none recorded)_\n"
    ]
  end

  defp stablecoin_routes_section(routes) when is_list(routes) do
    rendered = Enum.map(routes, &stablecoin_route_bullet/1)

    [
      "## Stablecoin route evidence\n",
      "\n",
      "Captured route evaluations: `",
      to_string(length(routes)),
      "`\n",
      "\n"
      | rendered
    ]
  end

  # Render one route as a key-value bullet group. Walks the
  # allowlist in fixed order; unknown keys (`quote_request`,
  # `legs`, `selector_metadata`, `policy_reasons`, `reason`, future
  # additions) are dropped on the floor by construction. Real
  # `after_ref` payloads come back from the DB as string-keyed
  # maps, but the in-memory shape is atom-keyed — `route_value/2`
  # tries both.
  defp stablecoin_route_bullet(%{} = route) do
    scalar_lines =
      Enum.flat_map(@stablecoin_route_safe_keys, fn key ->
        case route_value(route, key) do
          nil -> []
          v -> [["    - ", key, ": `", scalar_to_iodata(v), "`\n"]]
        end
      end)

    fee_lines = stablecoin_route_fee_lines(route_value(route, "fee_summary"))

    case scalar_lines ++ fee_lines do
      [] -> ["- _(route entry has no allowlisted fields)_\n"]
      lines -> ["- Route:\n" | lines]
    end
  end

  defp stablecoin_route_bullet(_), do: "- _(route entry has unexpected shape)_\n"

  defp stablecoin_route_fee_lines(nil), do: []

  defp stablecoin_route_fee_lines(%{} = fees) do
    rendered =
      Enum.flat_map(@stablecoin_route_safe_fee_keys, fn key ->
        case route_value(fees, key) do
          nil -> []
          v -> [["      - ", key, ": `", scalar_to_iodata(v), "`\n"]]
        end
      end)

    case rendered do
      [] -> []
      _ -> [["    - fee_summary:\n" | rendered]]
    end
  end

  defp stablecoin_route_fee_lines(_), do: []

  defp route_value(map, key) when is_binary(key) do
    case Map.fetch(map, key) do
      {:ok, v} -> v
      :error -> Map.get(map, String.to_existing_atom(key), nil)
    end
  rescue
    ArgumentError -> Map.get(map, key, nil)
  end

  defp scalar_to_iodata(v) when is_binary(v), do: v
  defp scalar_to_iodata(v) when is_integer(v), do: Integer.to_string(v)
  defp scalar_to_iodata(v) when is_float(v), do: Float.to_string(v)
  defp scalar_to_iodata(v) when is_boolean(v), do: to_string(v)
  defp scalar_to_iodata(v) when is_atom(v) and not is_nil(v), do: Atom.to_string(v)
  defp scalar_to_iodata(_), do: "(opaque)"

