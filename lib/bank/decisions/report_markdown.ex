      Map.get(event, :ts) || "(unknown)",
      "` | `",
      Map.get(event, :event_type) || "(unknown)",
      "` | `",
      to_string(Map.get(event, :actor) || "(unknown)"),
      "` | `",
      subject,
      "` |\n"
    ]
  end

